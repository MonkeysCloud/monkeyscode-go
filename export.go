// ToTranscript creates a structured JSON-serializable transcript.
func ToTranscript(result *Result) *Transcript {
	fc := make([]FileChange, len(result.FilesChanged))
	copy(fc, result.FilesChanged)

	return &Transcript{
		Version:    "1.0",
		ExportedAt: time.Now().UTC().Format(time.RFC3339),
		Result: TranscriptResult{
			Success:      result.Success,
			Status:       result.Status,
			Summary:      result.Summary,
			Model:        result.Model,
			Cost:         result.Cost,
			DurationMs:   result.DurationMs,
			Tokens:       result.Tokens,
			FilesChanged: fc,
		},
	}
}

// markdownToHTML does minimal markdown conversion (headings, lists, code, tables).
func markdownToHTML(md string) string {
	lines := strings.Split(md, "\n")
	var out strings.Builder
	inCode := false

	for _, line := range lines {
		if strings.HasPrefix(line, "```") {
			if inCode {
				out.WriteString("</code></pre>\n")
				inCode = false
			} else {
				out.WriteString("<pre><code>")
				inCode = true
			}
			continue
		}
		if inCode {
			out.WriteString(escapeHTML(line))
			out.WriteString("\n")
			continue
		}

		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			continue
		}
		if trimmed == "---" {
			out.WriteString("<hr>\n")
			continue
		}

		// Headings
		if strings.HasPrefix(trimmed, "# ") {
			out.WriteString(fmt.Sprintf("<h1>%s</h1>\n", trimmed[2:]))
		} else if strings.HasPrefix(trimmed, "## ") {
			out.WriteString(fmt.Sprintf("<h2>%s</h2>\n", trimmed[3:]))
		} else if strings.HasPrefix(trimmed, "### ") {
			out.WriteString(fmt.Sprintf("<h3>%s</h3>\n", trimmed[4:]))
		} else if strings.HasPrefix(trimmed, "- ") {
			out.WriteString(fmt.Sprintf("<li>%s</li>\n", inlineMarkdown(trimmed[2:])))
		} else if strings.HasPrefix(trimmed, "> ") {
			out.WriteString(fmt.Sprintf("<blockquote>%s</blockquote>\n", inlineMarkdown(trimmed[2:])))
		} else if strings.HasPrefix(trimmed, "|") {
			if strings.Contains(trimmed, "---") {
				continue
			}
			cells := strings.Split(trimmed, "|")
			out.WriteString("<tr>")
			for _, c := range cells {
				c = strings.TrimSpace(c)
				if c != "" {
					out.WriteString(fmt.Sprintf("<td>%s</td>", inlineMarkdown(c)))
				}
			}
			out.WriteString("</tr>\n")
		} else if strings.HasPrefix(trimmed, "*") && strings.HasSuffix(trimmed, "*") {
			out.WriteString(fmt.Sprintf("<em>%s</em>\n", trimmed[1:len(trimmed)-1]))
		} else {
			out.WriteString(fmt.Sprintf("<p>%s</p>\n", inlineMarkdown(line)))
		}
	}

	if inCode {
		out.WriteString("</code></pre>\n")
	}

	return out.String()
}

func inlineMarkdown(text string) string {
	text = escapeHTML(text)
	// Bold
	for strings.Contains(text, "**") {
		i := strings.Index(text, "**")
		j := strings.Index(text[i+2:], "**")
		if j < 0 {
			break
		}
		j += i + 2
		text = text[:i] + "<strong>" + text[i+2:j] + "</strong>" + text[j+2:]
	}
	// Inline code
	for strings.Contains(text, "`") {
		i := strings.Index(text, "`")
		j := strings.Index(text[i+1:], "`")
		if j < 0 {
			break
		}
		j += i + 1
		text = text[:i] + "<code>" + text[i+1:j] + "</code>" + text[j+1:]
	}
	return text
}

func escapeHTML(s string) string {
	s = strings.ReplaceAll(s, "&", "&amp;")
	s = strings.ReplaceAll(s, "<", "&lt;")
	s = strings.ReplaceAll(s, ">", "&gt;")
	return s
}
