package monkeyscode

import (
	"fmt"
	"strings"
	"time"
)

// ExportOptions configures export behavior.
type ExportOptions struct {
	Title            string
	IncludeToolCalls bool
	IncludeFileDiffs bool
	IncludeCost      bool
}

// DefaultExportOptions returns sensible defaults.
func DefaultExportOptions() ExportOptions {
	return ExportOptions{
		Title:            "MonkeysCode Agent Report",
		IncludeToolCalls: true,
		IncludeFileDiffs: true,
		IncludeCost:      true,
	}
}

// Transcript is a structured export of an agent result.
type Transcript struct {
	Version    string           `json:"version"`
	ExportedAt string           `json:"exportedAt"`
	Result     TranscriptResult `json:"result"`
}

// TranscriptResult is the result section of a transcript.
type TranscriptResult struct {
	Success      bool         `json:"success"`
	Status       string       `json:"status"`
	Summary      string       `json:"summary"`
	Model        string       `json:"model"`
	Cost         float64      `json:"cost"`
	DurationMs   int64        `json:"durationMs"`
	Tokens       TokenUsage   `json:"tokens"`
	FilesChanged []FileChange `json:"filesChanged"`
}

// ToMarkdown converts an agent result to a Markdown report.
func ToMarkdown(result *Result, opts ...ExportOptions) string {
	o := DefaultExportOptions()
	if len(opts) > 0 {
		o = opts[0]
	}

	var b strings.Builder

	b.WriteString(fmt.Sprintf("# %s\n\n", o.Title))

	// Summary
	b.WriteString("## Summary\n\n")
	status := "✅ Success"
	if !result.Success {
		status = "❌ Failed"
	}
	b.WriteString(fmt.Sprintf("- **Status**: %s\n", status))
	b.WriteString(fmt.Sprintf("- **Model**: %s\n", result.Model))
	if result.SessionID != "" {
		b.WriteString(fmt.Sprintf("- **Session**: `%s`\n", result.SessionID))
	}
	if result.DurationMs > 0 {
		b.WriteString(fmt.Sprintf("- **Duration**: %s\n", formatDuration(float64(result.DurationMs))))
	}
	b.WriteString("\n")

	// Agent output
	if result.Summary != "" {
		b.WriteString("## Agent Output\n\n")
		b.WriteString(result.Summary)
		b.WriteString("\n\n")
	}

	// Error
	if result.Error != "" {
		b.WriteString("## Error\n\n")
		b.WriteString(fmt.Sprintf("> %s\n\n", result.Error))
	}

	// Files changed
	if len(result.FilesChanged) > 0 && o.IncludeFileDiffs {
		b.WriteString("## Files Changed\n\n")
		b.WriteString(fmt.Sprintf("%d file(s) modified:\n\n", len(result.FilesChanged)))
		for _, f := range result.FilesChanged {
			b.WriteString(fmt.Sprintf("- `%s` (%s)\n", f.Path, f.Action))
			if f.Diff != "" {
				b.WriteString("\n```diff\n")
				b.WriteString(f.Diff)
				b.WriteString("\n```\n\n")
			}
		}
	}

	// Cost
	if o.IncludeCost {
		b.WriteString("## Cost & Usage\n\n")
		b.WriteString("| Metric | Value |\n")
		b.WriteString("|--------|-------|\n")
		b.WriteString(fmt.Sprintf("| Cost | $%.4f |\n", result.Cost))
		b.WriteString(fmt.Sprintf("| Input tokens | %d |\n", result.Tokens.Input))
		b.WriteString(fmt.Sprintf("| Output tokens | %d |\n", result.Tokens.Output))
		if result.Tokens.Thinking > 0 {
			b.WriteString(fmt.Sprintf("| Thinking tokens | %d |\n", result.Tokens.Thinking))
		}
		b.WriteString(fmt.Sprintf("| Total tokens | %d |\n", result.Tokens.Total))
		b.WriteString("\n")
	}

	// Footer
	b.WriteString("---\n")
	b.WriteString(fmt.Sprintf("*Generated by MonkeysCode SDK at %s*\n", time.Now().UTC().Format(time.RFC3339)))

	return b.String()
}

